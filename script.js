/*
   EXACTLY 12 PROJECTS ARE SHOWN INITIALLY.
   LOAD MORE REVEALS THE REST.
*/

const PROJECTS_PER_PAGE = 12;

let currentProjectFilter = 'All';

let showingAllProjects = false;


/* =========================================================
   RENDER PROJECT GALLERY
========================================================= */

function renderProjectGallery(filter = currentProjectFilter) {

    const gallery =
        document.getElementById('project-gallery');

    const loadMoreBtn =
        document.getElementById('load-more-projects');

    if (!gallery) {
        return;
    }


    currentProjectFilter = filter;


    /*
       FILTER PROJECTS
    */

    const filteredProjects =
        filter === 'All'
            ? projectItems
            : projectItems.filter(
                project =>
                    project.category === filter
            );


    /*
       SHOW ONLY FIRST 12
       UNTIL LOAD MORE IS CLICKED
    */

    const visibleProjects =
        showingAllProjects
            ? filteredProjects
            : filteredProjects.slice(
                0,
                PROJECTS_PER_PAGE
            );


    /*
       BUILD PROJECT CARDS
    */

    gallery.innerHTML =
        visibleProjects.map(project => `

            <article class="project-item">

                <div class="project-image">

                    <img
                        src="${project.image}"
                        alt="${project.title}"
                        loading="lazy"
                    >

                </div>

                <div class="project-meta">

                    <h3>
                        ${project.title}
                    </h3>

                </div>

            </article>

        `).join('');


    /*
       LOAD MORE BUTTON
    */

    if (loadMoreBtn) {

        const hasMoreProjects =
            filteredProjects.length >
            PROJECTS_PER_PAGE;

        if (
            hasMoreProjects &&
            !showingAllProjects
        ) {

            loadMoreBtn.style.display =
                'inline-flex';

        } else {

            loadMoreBtn.style.display =
                'none';

        }

    }

}


/* =========================================================
   PROJECT FILTERS
========================================================= */

function bindProjectFilters() {

    const filters =
        document.querySelectorAll(
            '.filter-btn'
        );


    filters.forEach(button => {

        button.addEventListener(
            'click',
            () => {

                filters.forEach(item => {

                    item.classList.toggle(
                        'active',
                        item === button
                    );

                });


                currentProjectFilter =
                    button.dataset.filter ||
                    'All';


                /*
                   WHEN CATEGORY CHANGES,
                   GO BACK TO FIRST 12
                */

                showingAllProjects = false;


                renderProjectGallery(
                    currentProjectFilter
                );

            }
        );

    });

}


/* =========================================================
   LOAD MORE PROJECTS
========================================================= */

function bindLoadMoreProjects() {

    const loadMoreBtn =
        document.getElementById(
            'load-more-projects'
        );


    if (!loadMoreBtn) {
        return;
    }


    loadMoreBtn.addEventListener(
        'click',
        () => {

            showingAllProjects = true;


            renderProjectGallery(
                currentProjectFilter
            );


            setTimeout(() => {

                loadMoreBtn.scrollIntoView({
                    behavior: 'smooth',
                    block: 'center'
                });

            }, 100);

        }
    );

}


